-- factorio-test suite for format.lua: the number and state helpers behind the
-- Blocks board and the build sheet. All game-free. See mod/tests/README.md to run.

local Format = require("format")

describe("slot_number", function()
  test("hides rates the engine would print as 0.0", function()
    assert.is_nil(Format.slot_number(0.05))
    assert.is_nil(Format.slot_number(0))
    assert.is_nil(Format.slot_number(nil))
  end)

  test("keeps rates from 0.1 up", function()
    assert.equals(0.1, Format.slot_number(0.1))
    assert.equals(4.61, Format.slot_number(4.61))
  end)
end)

describe("in_unit", function()
  test("scales a per-second rate into the block's unit", function()
    local v, suffix = Format.in_unit(0.5, "min")
    assert.equals(30, v)
    assert.equals("/min", suffix)
    v, suffix = Format.in_unit(0.01, "h")
    assert.equals(36, v)
    assert.equals("/h", suffix)
  end)

  test("falls back to per second for a missing or unknown unit", function()
    local v, suffix = Format.in_unit(2, nil)
    assert.equals(2, v)
    assert.equals("/s", suffix)
    assert.equals("/s", select(2, Format.in_unit(2, "fortnight")))
  end)
end)

describe("build_state", function()
  test("done when everything is placed (or more)", function()
    assert.equals("done", Format.build_state(15, 15))
    assert.equals("done", Format.build_state(20, 15))
  end)

  test("partial when some are placed", function()
    assert.equals("partial", Format.build_state(3, 15))
  end)

  test("none when nothing is placed or nothing is needed", function()
    assert.equals("none", Format.build_state(0, 15))
    assert.equals("none", Format.build_state(4, 0))
    assert.equals("none", Format.build_state(nil, nil))
  end)
end)

describe("num", function()
  test("trims trailing zeros and keeps small rates readable", function()
    assert.equals("1", Format.num(1))
    assert.equals("0.1", Format.num(0.10))
    assert.equals("0.06", Format.num(0.06))
    assert.equals("4.6", Format.num(4.61))
    assert.equals("673", Format.num(673.4))
    assert.equals("", Format.num(0))
  end)
end)

describe("power", function()
  test("picks kW, MW or GW", function()
    assert.equals("450 kW", Format.power(450e3))
    assert.equals("9.2 MW", Format.power(9.2e6))
    assert.equals("1.25 GW", Format.power(1.25e9))
  end)
end)

describe("matches", function()
  test("is a case-insensitive plain substring match", function()
    assert.is_true(Format.matches("Iron plate", "PLATE"))
    assert.is_true(Format.matches("Iron plate", ""))
    assert.is_false(Format.matches("Iron plate", "copper"))
    assert.is_true(Format.matches("a.b", ".")) -- no pattern magic
  end)
end)
